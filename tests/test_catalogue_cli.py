"""Catalogue generation, ``catalogue --check`` staleness, and the command-line interface,
run against a throw-away copy of the archive skeleton."""

from __future__ import annotations

import re

import pytest

from archive_factory import make_result


def test_empty_catalogue(archive):
    files = archive.afm.catalogue_files()
    assert set(files) == {"results.md", "topics.md", "verification.md"}
    for text in files.values():
        assert text.startswith("<!-- Generated by scripts/afm.py catalogue")
        assert "No contribution has been released yet." in text


def test_catalogue_contents(archive):
    make_result(archive.results, "AF-0001", "first-result", title="First synthetic result")
    make_result(archive.results, "AF-0002", "second-result", title="Second synthetic result",
                msc_primary="11J82", msc_secondary=("11Y60",))
    files = archive.afm.catalogue_files()
    res = files["results.md"]
    assert "| [AF-0001](../results/AF-0001-first-result/README.md) | First synthetic result | 11J72 | 1.0.0 | published |" in res
    assert res.index("AF-0001") < res.index("AF-0002")
    topics = files["topics.md"]
    assert "## 11J72" in topics and "## 11J82" in topics and "## 11Y60" in topics
    sec = topics.split("## 11Y60", 1)[1]
    assert "AF-0001" in sec and "AF-0002" in sec
    ver = files["verification.md"]
    assert ("| AF-0001 | published | Two plus two equals four. | `Sample.main_theorem` | complete | complete | standard"
            " | ai-internal |") in ver
    assert "## Published results (level V4)" in res and "No preprint." in res


def test_catalogue_ignores_non_result_directories(archive):
    make_result(archive.results, "AF-0001", "first-result")
    (archive.results / "notes").mkdir()
    (archive.results / "AF-12-bad").mkdir()
    assert [d.name for d in archive.afm.result_dirs()] == ["AF-0001-first-result"]


def test_catalogue_write_then_check(archive):
    make_result(archive.results, "AF-0001", "first-result")
    r = archive.run("catalogue", "--check")
    assert r.returncode == 1 and "stale catalogue files" in r.stdout
    r = archive.run("catalogue")
    assert r.returncode == 0 and "wrote 3 catalogue files" in r.stdout
    r = archive.run("catalogue", "--check")
    assert r.returncode == 0 and "catalogue up to date" in r.stdout


@pytest.mark.parametrize("change", ["edit-file", "delete-file", "new-result", "metadata"])
def test_catalogue_check_detects_staleness(archive, change):
    d = make_result(archive.results, "AF-0001", "first-result")
    assert archive.run("catalogue").returncode == 0
    if change == "edit-file":
        (archive.catalogue / "topics.md").write_text("hand edited\n")
    elif change == "delete-file":
        (archive.catalogue / "verification.md").unlink()
    elif change == "new-result":
        make_result(archive.results, "AF-0002", "second-result")
    else:
        text = (d / "result.toml").read_text().replace('version = "1.0.0"', 'version = "1.0.1"')
        (d / "result.toml").write_text(text)
    r = archive.run("catalogue", "--check")
    assert r.returncode == 1 and "stale catalogue files" in r.stdout


def test_catalogue_check_does_not_write(archive):
    make_result(archive.results, "AF-0001", "first-result")
    archive.run("catalogue", "--check")
    assert not archive.catalogue.exists()


def test_cli_list(archive):
    r = archive.run("list")
    assert r.returncode == 0 and "no contributions yet" in r.stdout
    make_result(archive.results, "AF-0001", "first-result", title="First synthetic result")
    r = archive.run("list")
    assert re.search(r"AF-0001\s+v1\.0\.0\s+published\s+First synthetic result", r.stdout)


def test_cli_check_all_and_one(archive):
    make_result(archive.results, "AF-0001", "first-result")
    bad = make_result(archive.results, "AF-0002", "second-result")
    (bad / "CHANGELOG.md").unlink()
    r = archive.run("check")
    assert r.returncode == 1
    assert "[PASS] check AF-0001-first-result" in r.stdout and "[FAIL] check AF-0002-second-result" in r.stdout
    assert archive.run("check", "AF-0001").returncode == 0
    assert archive.run("check", "AF-0002-second-result").returncode == 1


def test_cli_check_by_path(archive, tmp_path):
    d = make_result(tmp_path / "elsewhere", "AF-0003", "path-result")
    assert archive.run("check", str(d)).returncode == 0


def test_cli_check_unknown_result(archive):
    r = archive.run("check", "AF-9999")
    assert r.returncode != 0 and "no contribution matching 'AF-9999'" in r.stderr


def test_cli_check_with_no_results_passes(archive):
    assert archive.run("check").returncode == 0


def test_cli_usage_errors(archive):
    assert archive.run().returncode == 2
    assert archive.run("frobnicate").returncode == 2
    assert archive.run("lean").returncode == 2


def test_resolve_prefix_does_not_match_partial_ids(archive):
    make_result(archive.results, "AF-0010", "ten")
    with pytest.raises(SystemExit):
        archive.afm.resolve("AF-001")
    assert archive.afm.resolve("AF-0010").name == "AF-0010-ten"


def test_msc_table_loads(afm):
    table = afm.msc_table()
    assert len(table) > 6000 and table["11J72"].startswith("Irrationality")
    assert all(afm.MSC_RE.fullmatch(c) for c in table), "every official code is accepted by MSC_RE"
